const mongoose = require('mongoose');
const productVariantSchema = new mongoose.Schema(
    {
        productId:{
            type:mongoose.Schema.Types.ObjectId,
            ref:'Product',
            required:true
        },
        attributes:[
            {
                name:{
                    type:String,
                    required:true,
                    trim:true
                },
                value:{
                    type:String,
                    required:true,
                    trim:true
                }
            }
        ],
        price:{
            type:Number,
            required:true,
            min:0
        },
        stock:{
            type:Number,
            required:true,
            min:0,
            default:0
        },
        isActive:{
            type:Boolean,
            default:true
        }
    },
    {
        timestamps:true
    }
);
module.exports = mongoose.model('ProductVariant',productVariantSchema);