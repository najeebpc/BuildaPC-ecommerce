const mongoose = require('mongoose');

const productSchema = new mongoose.Schema(
    {
        name:{
            type:String,
            required:true,
            trim: true
        },
        basePrice:{
            type:Number,
            required:true,
            min:0
        },
        stockLevel:{
            type:Number,
            required:true,
            default:0
        },
        productType:{
            type:String,
            enum:['component','pre_built'],
            required:true
        },
        categoryId:{
            type:mongoose.Schema.Types.ObjectId,
            ref:'Category',
            default:null
        },
        primaryImage:{
            type:String,
            required:true
        },
        secondaryImages:{
            type:[String],
            default:[]
        },
        description:{
            type:String,
            trim:true
        },
        features:{
            type:String,
            default:''
        },
        specifications:[
            {
            name:String,
            value:String
            }
        ],
        relatedProducts:[
            {
                type:mongoose.Schema.Types.ObjectId,
                ref:'product'
            }
        ],
        isListed:{
            type:Boolean,
            default:false
        },
        isDeleted:{
            type:Boolean,
            default:false
        }
    },
    {timestamps:true}
);
module.exports= mongoose.model('Product',productSchema);